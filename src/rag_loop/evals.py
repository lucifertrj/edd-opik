from dataclasses import replace
from pathlib import Path
from typing import Any

import opik
from opik.evaluation import evaluate
from opik.evaluation.metrics import AnswerRelevance, GEval, Hallucination
from opik.evaluation.metrics.score_result import ScoreResult
from opik.evaluation.test_result import TestResult

from .config import Settings, get_settings
from .dataset import load_validated_items
from .rag import answer_question

DATASET_NAME = "aircraft-systems"
DATASET_PATH = Path("evals/seed.jsonl")

HALLUCINATION_METRIC_NAME = "hallucination_metric"
CLEAN_NEGATIVE_HALLUCINATION_THRESHOLD = 0.5


class _AnswerQualityMetric(GEval):
    """GEval only scores `output` in isolation, never the question it answers.

    That leaves it unable to tell a correct refusal ("not in the source") from
    an incomplete answer, since it doesn't know what was asked. Folding the
    question into the text handed to the parent's scorer fixes that without
    duplicating GEval's prompt-building/parsing internals.
    """

    def score(self, input: str, output: str, **ignored_kwargs: Any) -> ScoreResult:
        return super().score(output=f"Question: {input}\nAnswer: {output}")


def _answer_quality_metric(settings: Settings) -> GEval:
    return _AnswerQualityMetric(
        name="answer_quality",
        task_introduction=(
            "Evaluate whether the Answer is a high-quality response to the Question. The "
            "Answer was generated by a RAG system that can only draw on a specific source "
            "document, not general knowledge."
        ),
        evaluation_criteria=(
            "The response must be complete enough to address the question, direct, and clear. "
            "If the question cannot be answered from the source document, a response that says "
            "so directly (rather than guessing or fabricating an answer) is high quality, not "
            "incomplete."
        ),
        model=settings.eval_model,
        temperature=1,
    )


def _clean_negative_recall(test_results: list[TestResult]) -> ScoreResult:
    """Check the app doesn't fabricate answers on known-unanswerable goldens.

    `label` (evals/seed.jsonl) records whether `expected_output` is actually
    grounded in the source document - a property of the golden itself, fixed
    at labeling time. It does NOT predict whether a live run's output will
    hallucinate, so it can't be compared to the Hallucination metric item by
    item in general. But `label == 0` items are unanswerable by construction,
    so the only correct live behavior is a refusal, which the Hallucination
    metric should then score low. That's the one place `label` and a live
    metric are actually comparable - a recall check over the held-out
    clean-negative set.
    """
    negatives = [
        result
        for result in test_results
        if result.test_case.dataset_item_content.get("label") == 0
    ]
    if not negatives:
        return ScoreResult(
            name="clean_negative_recall",
            value=0.0,
            reason="No label=0 items in this dataset version.",
            scoring_failed=True,
        )

    caught = 0
    for result in negatives:
        hallucination_score = next(
            (
                score.value
                for score in result.score_results
                if score.name == HALLUCINATION_METRIC_NAME
            ),
            None,
        )
        if hallucination_score is not None and hallucination_score < CLEAN_NEGATIVE_HALLUCINATION_THRESHOLD:
            caught += 1

    recall = caught / len(negatives)
    return ScoreResult(
        name="clean_negative_recall",
        value=recall,
        reason=(
            f"{caught}/{len(negatives)} known-unanswerable questions were answered without "
            "hallucinating (hallucination_metric < "
            f"{CLEAN_NEGATIVE_HALLUCINATION_THRESHOLD})."
        ),
    )


def load_seed_items(path: Path = DATASET_PATH) -> list[dict[str, Any]]:
    return load_validated_items(path)


def load_dataset(
    client: opik.Opik | None = None,
    version_name: str | None = None,
):
    client = client or opik.Opik()
    dataset = client.get_dataset(name=DATASET_NAME)
    return dataset.get_version_view(version_name) if version_name else dataset


def create_seed_dataset(path: Path = DATASET_PATH) -> str:
    client = opik.Opik()
    dataset = client.get_or_create_dataset(name=DATASET_NAME)
    dataset.insert(load_seed_items(path))
    return dataset.get_current_version_name()


def create_dataset_from_traces(items: list[dict[str, Any]]) -> str:
    client = opik.Opik()
    dataset = client.get_or_create_dataset(name=DATASET_NAME)
    dataset.insert(items)
    return dataset.get_current_version_name()


def run_evaluation(
    settings: Settings | None = None,
    experiment_name: str | None = None,
    dataset_version: str | None = None,
):
    settings = settings or get_settings()
    client = opik.Opik()
    dataset = load_dataset(client, dataset_version)

    def task(item: dict[str, Any]) -> dict[str, Any]:
        result = answer_question(item["input"], settings)
        return {
            "output": result["answer"],
            "context": result["context"],
        }

    return evaluate(
        experiment_name=experiment_name or f"rag-{settings.chat_model}-{settings.retrieval_k}",
        dataset=dataset,
        task=task,
        scoring_metrics=[
            AnswerRelevance(model=settings.eval_model),
            Hallucination(model=settings.eval_model),
            _answer_quality_metric(settings),
        ],
        experiment_scoring_functions=[_clean_negative_recall],
        task_threads=1,
    )


def run_config_loop(configurations: list[dict[str, Any]], settings: Settings | None = None):
    settings = settings or get_settings()
    dataset_version = load_dataset().get_current_version_name()
    results = []
    for configuration in configurations:
        experiment_settings = replace(
            settings,
            chat_model=configuration.get("chat_model", settings.chat_model),
            retrieval_k=configuration.get("retrieval_k", settings.retrieval_k),
        )
        results.append(
            run_evaluation(
                experiment_settings,
                experiment_name=configuration["name"],
                dataset_version=dataset_version,
            )
        )
    return results
